-- ------------------------------------------------------------------------------
-- 3. ITEMS TABLE
-- Core table tracking Lost and Found items.
-- Connected to: users (reported_by) and categories (category_id)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    location TEXT NOT NULL,
    item_type TEXT NOT NULL CHECK (item_type IN ('Lost', 'Found')),
    category_id INT REFERENCES public.categories(id) ON DELETE SET NULL,
    reported_by TEXT NOT NULL REFERENCES public.users(email) ON UPDATE CASCADE ON DELETE CASCADE,
    image_url TEXT,
    status TEXT NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Claimed', 'Resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Index for search performance
CREATE INDEX IF NOT EXISTS idx_items_status ON public.items(status);
CREATE INDEX IF NOT EXISTS idx_items_item_type ON public.items(item_type);
CREATE INDEX IF NOT EXISTS idx_items_reported_by ON public.items(reported_by);

-- ------------------------------------------------------------------------------
-- 4. CLAIMS TABLE
-- Relational table connecting Items with Users who claim them.
-- Keeps full verification audit history.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES public.items(id) ON DELETE CASCADE,
    claimant_email TEXT NOT NULL REFERENCES public.users(email) ON UPDATE CASCADE ON DELETE CASCADE,
    claim_message TEXT,
    proof_image_url TEXT,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_claims_item ON public.claims(item_id);
CREATE INDEX IF NOT EXISTS idx_claims_claimant ON public.claims(claimant_email);

-- ------------------------------------------------------------------------------
-- 5. AUDIT / ACTIVITY LOG TABLE
-- Relational log tracking lifecycle events (Reported, Claimed, Resolved, Deleted)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT REFERENCES public.items(id) ON DELETE CASCADE,
    performed_by TEXT REFERENCES public.users(email) ON UPDATE CASCADE ON DELETE SET NULL,
    action TEXT NOT NULL,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------------------------
-- 6. SUPABASE STORAGE BUCKET CONFIGURATION FOR IMAGES
-- Creates a public bucket named 'item-images'
-- ------------------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('item-images', 'item-images', true)
ON CONFLICT (id) DO NOTHING;

-- Policy: Allow public read access to all images in 'item-images'
CREATE POLICY "Public Access"
ON storage.objects FOR SELECT
USING (bucket_id = 'item-images');

-- Policy: Allow uploads to 'item-images' bucket
CREATE POLICY "Allow Uploads"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'item-images');

-- Policy: Allow updates to 'item-images' bucket
CREATE POLICY "Allow Updates"
ON storage.objects FOR UPDATE
USING (bucket_id = 'item-images');

